let current = null;

export async function initLang() {
  const { lang } = await chrome.storage.local.get({ lang: "zh" });
  current = DICT[lang] ? lang : "zh";
  return current;
}

export function getLang() {
  return current || "zh";
}

export async function setLang(lang) {
  current = DICT[lang] ? lang : "zh";
  await chrome.storage.local.set({ lang: current });
}

export function t(key, vars) {
  const dict = DICT[current || "zh"] || DICT.zh;
  let s = dict[key] ?? DICT.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
